// =====================================================
// DISPLAY RESULT
// =====================================================

function displayResult(
    student,
    level,
    result
) {

    document.getElementById(
        "resultStudent"
    ).innerText =
        "Student: " +
        student.name;


    document.getElementById(
        "resultDifficulty"
    ).innerText =
        "Difficulty: " +
        level.toUpperCase();


    document.getElementById(
        "score"
    ).innerText =
        result.score;


    document.getElementById(
        "total"
    ).innerText =
        result.total;


    document.getElementById(
        "correct"
    ).innerText =
        result.correct;


    document.getElementById(
        "wrong"
    ).innerText =
        result.wrong;


    document.getElementById(
        "unanswered"
    ).innerText =
        result.unanswered;


    const accuracy =
        (
            result.correct /
            result.total
        ) * 100;


    document.getElementById(
        "accuracyBar"
    ).style.width =
        accuracy + "%";


    document.getElementById(
        "accuracyText"
    ).innerText =
        accuracy.toFixed(1) +
        "%";


    let performance;


    if (result.score >= 16) {

        performance =
            "Excellent Performance! 🎉";

    }

    else if (result.score >= 12) {

        performance =
            "Good Performance! 👍";

    }

    else if (result.score >= 8) {

        performance =
            "Average Performance";

    }

    else {

        performance =
            "Needs Improvement";

    }


    document.getElementById(
        "performance"
    ).innerText =
        performance;


    showWrongAnswers(
        result.answers,
        level
    );
}


// =====================================================
// WRONG ANSWER ANALYSIS
// =====================================================

function showWrongAnswers(
    userAnswers,
    level
) {

    const container =
        document.getElementById(
            "wrongAnswers"
        );


    const questions =
        questionBank[level];


    let foundWrong = false;


    questions.forEach(
        function(q, index) {

            const userAnswer =
                userAnswers[index];


            if (
                userAnswer !== undefined &&
                userAnswer !== q.answer
            ) {

                foundWrong = true;


                const div =
                    document.createElement(
                        "div"
                    );


                div.className =
                    "wrong-item";


                div.innerHTML = `

                    <h3>
                        Question ${index + 1}
                    </h3>

                    <p>
                        <strong>
                            ${q.question}
                        </strong>
                    </p>

                    <p class="your-answer">
                        Your Answer:
                        ${q.options[userAnswer]}
                    </p>

                    <p class="correct-answer">
                        Correct Answer:
                        ${q.options[q.answer]}
                    </p>

                    <p class="explanation">
                        Explanation:
                        ${q.explanation}
                    </p>

                `;


                container.appendChild(
                    div
                );
            }

        }
    );


    if (!foundWrong) {

        container.innerHTML = `

            <p class="correct-answer">

                🎉 Excellent!

                No wrong answers.

            </p>

        `;
    }
}


